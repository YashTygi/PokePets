#!/usr/bin/env python3
"""Rebuild the website's sprite data from the app's SpriteCollab sheets.

    python3 bin/build-site-sprites.py

Copies each form's sheets from PokePets/ into docs/assets/sprites/ and writes docs/assets/sheets.js
(frame size, frame timings in 1/60 s ticks, and where the feet and the top of the art sit in the
Right and Down rows), so the page needs no XML fetch and no canvas reads (both break on file://).
Standard library only.
"""
import json, re, shutil, struct, sys, zlib
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "PokePets"
OUT = ROOT / "docs" / "assets"
FORMS = ["pichu", "pikachu", "raichu", "raichu-alola", "gastly", "haunter", "gengar"]
RIGHT, DOWN = 2, 0   # SpriteCollab rows: Down, DownRight, Right, UpRight, Up, UpLeft, Left, DownLeft


def read_png(path):
    """Width, height and the alpha of every pixel (8-bit RGBA, non-interlaced: what SpriteCollab ships)."""
    data = path.read_bytes()
    pos, idat = 8, b""
    while pos < len(data):
        n, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        if kind == b"IHDR":
            w, h, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", body)
            assert (depth, color, interlace) == (8, 6, 0), f"{path.name}: expected 8-bit RGBA"
        elif kind == b"IDAT":
            idat += body
        pos += 12 + n
    raw, stride, rows, prev = zlib.decompress(idat), w * 4, [], bytearray(w * 4)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b = prev[i]
            c = prev[i - 4] if i >= 4 else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line)
        prev = line
    return w, h, [bytes(r[3::4]) for r in rows]


def extent(alpha, top, height):
    """First and last opaque row (frame coordinates) of a sheet row, over every frame."""
    hit = [y for y in range(height) if any(a > 25 for a in alpha[top + y])]
    return (hit[0], hit[-1] + 1) if hit else (0, height)


def build():
    (OUT / "sprites").mkdir(parents=True, exist_ok=True)
    sheets = {}
    for form in FORMS:
        root = ET.parse(SRC / f"{form}-anim.xml").getroot()
        info = {}
        for a in root.find("Anims"):
            name = a.findtext("Name")
            if a.find("CopyOf") is not None:
                info[name] = {"copy": a.findtext("CopyOf")}
            else:
                info[name] = {"w": int(a.findtext("FrameWidth")), "h": int(a.findtext("FrameHeight")),
                              "t": [int(d.text) for d in a.find("Durations")]}
        sheets[form] = {}
        for name, a in info.items():
            src = info[a["copy"]] if "copy" in a else a
            stem = (a.get("copy") or name).lower()
            png = SRC / f"{form}-{stem}.png"
            if not png.exists() or "w" not in src:
                continue
            w, h, alpha = read_png(png)
            rows = h // src["h"]
            assert w == src["w"] * len(src["t"]), f"{png.name}: sheet is {w} wide, XML says {src['w'] * len(src['t'])}"
            entry = {"f": f"{form}-{stem}", "w": src["w"], "h": src["h"], "t": src["t"], "rows": rows}
            for key, row in (("right", RIGHT), ("down", DOWN)):
                top, bottom = extent(alpha, (row if row < rows else 0) * src["h"], src["h"])
                entry[key] = [top, bottom]          # first opaque row, and the feet line (rows from the frame's top)
            sheets[form][name] = entry
            shutil.copyfile(png, OUT / "sprites" / png.name)
    js = "/* generated by bin/build-site-sprites.py: do not edit */\nwindow.POKE_SHEETS = " + json.dumps(sheets, separators=(",", ":")) + ";\n"
    (OUT / "sheets.js").write_text(js)
    print(f"{sum(len(v) for v in sheets.values())} animations, {len(list((OUT / 'sprites').iterdir()))} sheets")


if __name__ == "__main__":
    build()
